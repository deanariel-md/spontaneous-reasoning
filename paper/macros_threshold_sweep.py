"""Macros and table of the threshold sweep for "long" (exploratory), from results/threshold_sweep/threshold_sweep.json (scripts/threshold_sweep.py).

threshold_sweep_results(root) reads the JSON, or returns None until it exists; threshold_sweep_macros(R) returns
{name: value}; threshold_sweep_table(R) returns the text of paper/tables/threshold_sweep.tex (a tabular, no table float).

  thr<T><Cut>VarLongPct   the long part's share of the between-model variance of requested minus forced accuracy, %,
                          0 dp, every distinct configuration once (basis of bmixDec<T>VarLongPct; a covariance share,
                          so it can be below 0 or above 100)
  thr<T><Cut>RevPairs     pairs reversed between the observed gain over the requested arm and (1 - w)(C - F), w at the
                          cutoff, discovery means (basis of bmix<T>RevCorr)
  thr<T><Cut>RevOf        the pair total (basis of bmix<T>Pairs)
  thr<T><Cut>MeanWPct     mean w over models, %, 0 dp, discovery draws (basis of bmix<T>WMeanPct; the same under both
                          scorings, given under both names)
each strict, and with the suffix Content for content scoring. T: Gsm, Math, Bbh, Hq; Cut: Eight, Sixteen, ThirtyTwo,
SixtyFour (HotpotQA: Sixteen and SixtyFour only).
"""
from __future__ import annotations

import json
import math
import os

PATH = os.path.join("results", "threshold_sweep", "threshold_sweep.json")
TASK_TAG = {"gsm8k": "Gsm", "math": "Math", "bbh": "Bbh", "hotpot": "Hq"}
TASK_NAME = {"gsm8k": "GSM8K", "math": "MATH-500", "bbh": "BIG-Bench Hard", "hotpot": "HotpotQA"}
CUT_WORD = {8: "Eight", 16: "Sixteen", 32: "ThirtyTwo", 64: "SixtyFour"}
SCORE_SUFFIX = {"strict": "", "content": "Content"}
TABLE_CUTS = (8, 16, 32, 64)


def num(x, nd=0):
    """x to nd decimals with a math-mode minus; "--" for None, NaN or infinity (paper/make_numbers.py's format)."""
    try:
        v = float(x)
    except (TypeError, ValueError):
        return "--"
    if not math.isfinite(v):
        return "--"
    if round(v, nd) == 0:
        v = 0.0
    return f"{v:.{nd}f}".replace("-", "$-$")


def threshold_sweep_results(root: str):
    p = os.path.join(root, PATH)
    if not os.path.exists(p):
        return None
    with open(p, encoding="utf-8") as fh:
        return json.load(fh)


def _cell(T, cut, score):
    """(VarLongPct, RevPairs, RevOf, MeanWPct) strings at one cutoff and score."""
    r = T["by_cut"][str(cut)]
    s = r[score]
    v = s["variance_share_long"]
    return (num(None if v is None else 100 * v, 0), str(s["reversed_corrected"]), str(s["pairs"]),
            num(r["mean_w_pct"], 0))


def threshold_sweep_macros(R) -> dict:
    if not R:
        return {}
    m = {}
    for task, T in R["tasks"].items():
        tt = TASK_TAG[task]
        for c in T["cuts"]:
            for sc, suf in SCORE_SUFFIX.items():
                var, rev, of, w = _cell(T, c, sc)
                stem = "thr" + tt + CUT_WORD[int(c)]
                for q, val in (("VarLongPct", var), ("RevPairs", rev), ("RevOf", of), ("MeanWPct", w)):
                    k = stem + q + suf
                    if k in m:
                        raise ValueError(f"macro {k} set twice")
                    m[k] = val
    bad = [k for k in m if not k.isalpha()]
    if bad:
        raise ValueError(f"macro names must be letters only: {bad}")
    return m


def threshold_sweep_table(R) -> str:
    """Rows benchmark x scoring; per cutoff the long share of the variance (%), the reversed pairs under the corrected
    gain and the mean w (%); the pair total in its own column. A cutoff not computed for a benchmark prints --."""
    n = len(TABLE_CUTS)
    L = ["% Generated by scripts/threshold_sweep.py (paper/macros_threshold_sweep.threshold_sweep_table) from "
         "results/threshold_sweep/threshold_sweep.json; exploratory.",
         "% Long: share (%) of the between-model variance of requested minus forced accuracy from long requested answers "
         "(all distinct configurations). Rev.: pairs reversed between the gain over the requested arm and (1-w)(C-F) "
         "(discovery means), of Pairs. w: mean over models (%, discovery draws). HotpotQA: 16 and 64 tokens only (--).",
         r"\begin{tabular}{@{}llr" + "rrr" * n + "@{}}", r"\toprule",
         " & & & " + " & ".join(rf"\multicolumn{{3}}{{c}}{{{c} tokens}}" for c in TABLE_CUTS) + r"\\",
         "".join(rf"\cmidrule({'lr' if i < n - 1 else 'l'}){{{4 + 3 * i}-{6 + 3 * i}}}" for i in range(n)),
         "Benchmark & Scoring & Pairs & " + " & ".join(r"Long (\%) & Rev. & $\bar w$ (\%)" for _ in TABLE_CUTS) + r"\\",
         r"\midrule"]
    for task, T in R["tasks"].items():
        for j, (sc, _) in enumerate(SCORE_SUFFIX.items()):
            cells, pairs = [], set()
            for c in TABLE_CUTS:
                if str(c) not in T["by_cut"]:
                    cells += ["--", "--", "--"]
                    continue
                var, rev, of, w = _cell(T, c, sc)
                pairs.add(of)
                cells += [var, rev, w]
            if len(pairs) != 1:
                raise ValueError(f"{task} {sc}: the pair total differs between cutoffs {sorted(pairs)}")
            L.append(f"{TASK_NAME[task] if j == 0 else ''} & {sc} & {pairs.pop()} & " + " & ".join(cells) + r"\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(L) + "\n"
