r"""Request files for Cheng et al.'s eight-exemplar chain of thought against zero-shot
chain of thought on GSM8K-29, every configuration of the collection's frozen sampler (24 discovery and 24 validation
draws), all 1,319 test items, as a full setting with a validation split.

Only the eight-shot arm is generated. The zero-shot arm is the collection's chain-of-thought arm: for every model,
configuration and item, the zero-shot frame of src/reproduction.transport_arms filled with the item must equal the
collection's request messages byte for byte, or the build refuses. The eight-shot arm is the same frame preceded by
the authors' eight exemplar turns (manifests/cheng_exemplars.json), so the two arms differ only in the exemplars.

    .\.venv\Scripts\python.exe scripts\build_exemplar_requests.py

Writes data/requests/exemplar/gsm8k/<model_key>.parquet, data/requests/exemplar/gsm8k/build_record.json and
config/models_exemplar.yaml. Nothing here reads an outcome.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src import gsm8k, reproduction as rp  # noqa: E402
from src.sampling import sha256_json  # noqa: E402

OUT = ROOT / "data" / "requests" / "exemplar" / "gsm8k"
ARM = "eight_shot_cot"
# max_position_embeddings 4,096 in the pinned config.json (the runner's pilot refuses a max_model_len above it)
NATIVE_4K = {"llama-2-7b-chat-hf", "llama-2-13b-chat-hf", "phi-3-mini-4k-instruct", "phi-3-medium-4k-instruct"}
COLLECTION = {"gsm8k": ROOT / "data" / "requests" / "gsm8k", "gsm8k_ext": ROOT / "data" / "requests" / "gsm8k_ext"}


def collection_requests(model_key: str) -> pd.DataFrame:
    for d in (COLLECTION["gsm8k"], COLLECTION["gsm8k_ext"] / f"collection_{model_key}"):
        f = d / f"{model_key}.parquet"
        if f.exists():
            return pd.read_parquet(f, columns=["request_id", "arm", "config_id", "item_id", "messages_json"])
    raise SystemExit(f"{model_key}: no collection request file in {', '.join(str(d) for d in COLLECTION.values())}")


def write_registry(panel: list[str]) -> dict:
    """config/models_exemplar.yaml: the panel's entries of config/models.yaml and config/models_extension.yaml
    unchanged except max_model_len, raised to 8,192 so that an eight-shot prompt (up to about 1,600 tokens) fits
    beside the collection's 3,072-token chain-of-thought cap. Checkpoints whose native context is 4,096 tokens keep
    4,096 and run with config/decoding_exemplar_4k.yaml."""
    import yaml
    entries = {}
    for name in ("models.yaml", "models_extension.yaml"):
        entries.update((yaml.safe_load(open(ROOT / "config" / name, encoding="utf-8"))["dataset2"]["models"]))
    out = {k: dict(entries[k]) for k in panel}
    for k, e in out.items():
        e["max_model_len"] = 4096 if k in NATIVE_4K else 8192
    head = ("# Generated by scripts/build_exemplar_requests.py.\n# The GSM8K-29 panel's registry entries unchanged except max_model_len (8,192; 4,096 for the "
            "checkpoints\n# whose native context is 4,096 tokens). Do not edit by hand.\n")
    p = ROOT / "config" / "models_exemplar.yaml"
    p.write_text(head + yaml.safe_dump({"dataset2": {"models": out}}, sort_keys=False, allow_unicode=True),
                 encoding="utf-8")
    return {"path": "config/models_exemplar.yaml", "sha256": rp.sha256_file(p), "native_4k": sorted(NATIVE_4K)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--models", nargs="*", help="model keys (default: the GSM8K-29 panel)")
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args(argv)
    sampler = json.load(open(ROOT / "manifests" / "sampler_gsm8k.json", encoding="utf-8"))
    configs = sorted(set(map(str, sampler["discovery_config_ids"])) | set(map(str, sampler["validation_config_ids"])))
    bank = rp.load_json("manifests/gsm8k_bank.json")
    prompts = rp.load_json("manifests/cheng_exemplars.json")
    items = gsm8k.load_gsm8k("test")
    res = json.load(open(ROOT / "results" / "dataset2" / "gsm8k30.json", encoding="utf-8"))
    panel = list(res["models"])
    models = a.models or panel
    if set(models) - set(panel):
        raise SystemExit(f"not in the GSM8K-29 panel: {sorted(set(models) - set(panel))}")
    arms = {c: rp.transport_arms(bank, c, prompts) for c in configs}
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    record = {"schema_version": "1", "kind": "exemplar", "split": "test",
              "purpose": "eight-exemplar against zero-shot chain of thought on GSM8K-29",
              "excluded_from_main": False, "arms": [ARM],
              "zero_shot_arm": "the collection's zero_shot_cot outputs (data/requests/gsm8k*, byte-identical messages)",
              "bank": {"path": "manifests/gsm8k_bank.json", "sha256": rp.sha256_file(ROOT / "manifests" / "gsm8k_bank.json")},
              "sampler": {"path": "manifests/sampler_gsm8k.json",
                          "file_sha256": rp.sha256_file(ROOT / "manifests" / "sampler_gsm8k.json")},
              "prompts": {"path": "manifests/cheng_exemplars.json",
                          "sha256": rp.sha256_file(ROOT / "manifests" / "cheng_exemplars.json")},
              "configurations": configs, "items": {"n": int(len(items)), "canonical_sha256": gsm8k.canonical_sha256(items)},
              "models": {}}
    for m in models:
        df = rp.build_requests(m, arms, items)
        zs = df[df["arm"] == "zero_shot_cot"][["request_id", "messages_json"]]
        col = collection_requests(m)
        col = col[(col["arm"] == "zero_shot_cot") & col["config_id"].isin(configs)][["request_id", "messages_json"]]
        j = zs.merge(col, on="request_id", how="outer", suffixes=("_built", "_collection"), indicator=True)
        if (j["_merge"] != "both").any() or (j["messages_json_built"] != j["messages_json_collection"]).any():
            bad = j[(j["_merge"] != "both") | (j["messages_json_built"] != j["messages_json_collection"])]
            raise SystemExit(f"{m}: {len(bad)} zero-shot requests differ from the collection's (first: "
                             f"{bad['request_id'].iloc[0]})")
        df = df[df["arm"] == ARM].reset_index(drop=True)
        f = out / f"{m}.parquet"
        df.to_parquet(f, index=False)
        record["models"][m] = {"requests_file": f.name, "requests_sha256": rp.sha256_file(f), "n_requests": int(len(df)),
                               "zero_shot_checked": int(len(j))}
        print(f"{m:<36} {len(df):>6} eight-shot requests; {len(j)} zero-shot requests match the collection")
    record["registry"] = write_registry(panel)
    record["sha256"] = sha256_json({k: v["requests_sha256"] for k, v in record["models"].items()})
    (out / "build_record.json").write_text(json.dumps(record, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {out / 'build_record.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
